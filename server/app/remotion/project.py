"""Build a job's Remotion project (docs/REMOTION_CONTRACT.md §2-§3, part A).

write_project: template -> assets copied into public/ -> one Opus call picks a shotcraft card
per scene -> one Opus call per scene (4 in parallel) writes src/scenes/<id>.tsx -> type-check
and a midpoint still per scene, one regeneration with the error text, then the TitleCard
fallback (§3.8). Writes src/scenes/index.ts and src/data/timeline.json; sets scenes[i]['card'].
"""
from __future__ import annotations

import json
import re
import shutil
import time
import uuid
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Callable

from . import catalog, generate, render

FALLBACK_CARD = "fallback/title-card"
FPS = 30
WORKERS = 4


def file_stem(sid: str) -> str:
    """Scene module file name (lower-case scene id, safe characters only)."""
    stem = re.sub(r"[^a-z0-9_]+", "_", sid.lower()).strip("_") or "scene"
    return stem if not stem[0].isdigit() else f"s{stem}"


def ident(stem: str) -> str:
    return stem if re.fullmatch(r"[A-Za-z_]\w*", stem) else f"s_{stem}"


def stems(scenes: list) -> list[str]:
    out, seen = [], set()
    for s in scenes:
        st = file_stem(s["id"])
        base, k = st, 2
        while st in seen:
            st, k = f"{base}_{k}", k + 1
        seen.add(st)
        out.append(st)
    return out


def index_ts(scenes: list) -> str:
    sts = stems(scenes)
    lines = ["// GENERATED by app/remotion/project.py (docs/REMOTION_CONTRACT.md §3).",
             'import type { SceneModule } from "../types";']
    lines += [f'import * as {ident(st)} from "./{st}";' for st in sts]
    body = ", ".join(f"{json.dumps(s['id'], ensure_ascii=False)}: {ident(st)}"
                     for s, st in zip(scenes, sts))
    lines.append(f"\nexport const SCENES: Record<string, SceneModule> = {{ {body} }};")
    return "\n".join(lines) + "\n"


def timeline(scenes: list, frames: list, w: int, h: int, background: str, cards: dict) -> dict:
    out, t = [], 0
    for i, (s, n) in enumerate(zip(scenes, frames)):
        n = int(n)
        out.append({"id": s["id"], "label": f"S{i + 1} {s.get('title') or s['id']}",
                    "from": t, "duration": n, "card": cards.get(s["id"], FALLBACK_CARD)})
        t += n
    return {"fps": FPS, "width": w, "height": h, "background": background,
            "revision": f"{time.strftime('%Y%m%d-%H%M%S')}-{uuid.uuid4().hex[:6]}", "scenes": out}


def fallback_tsx(s: dict, look: dict) -> str:
    narr = (s.get("narration") or "").strip()
    defaults = {"title": s.get("title") or s["id"], "subtitle": narr[:60] + ("…" if len(narr) > 60 else ""),
                "color": look.get("ink", "#f4f1ea"), "accent": look.get("accent", "#ffd166"),
                "background": look.get("background", "#101828")}
    return ("// FALLBACK scene (docs/REMOTION_CONTRACT.md §3.8): the generated module failed.\n"
            'export { Scene, schema } from "../lib/TitleCard";\n'
            'import { DEFAULTS as BASE } from "../lib/TitleCard";\n'
            f"export const DEFAULTS = {{ ...BASE, ...{json.dumps(defaults, ensure_ascii=False)} }};\n")


def tsc_errors(text: str, sts: list[str]) -> dict[str, str]:
    """Map tsc output lines to scene stems. index.ts errors naming "./<stem>" count for it."""
    errs: dict[str, list] = {}
    for ln in text.splitlines():
        m = re.match(r"src/scenes/([\w-]+)\.tsx?\(\d+,\d+\): error", ln)
        st = m.group(1) if m else None
        if st == "index":
            st = next((x for x in sts if f'"./{x}"' in ln or f"'./{x}'" in ln), None)
        if st in sts:
            errs.setdefault(st, []).append(ln)
    return {k: "\n".join(v[:30]) for k, v in errs.items()}


def uniform(png: Path, tol: int = 6) -> bool:
    """True when the frame is (almost) one colour: a blank or failed render."""
    from PIL import Image
    with Image.open(png) as im:
        ext = im.convert("RGB").resize((96, 54)).getextrema()
    return all(hi - lo <= tol for lo, hi in ext)


def _copy(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.is_symlink() or dst.exists():
        dst.unlink()
    shutil.copyfile(src, dst)  # a real copy: Remotion's static server refuses symlinks


def _tail(p: Path, n: int = 4000) -> str:
    t = p.read_text(errors="replace") if p.exists() else ""
    t = re.sub(r"\x1b\[[0-9;]*m", "", t)
    return t[-n:]


class _Gen:
    def __init__(self, job, proj, frames, w, h, images, clips, background, context, log):
        self.scenes = job["scenes"]
        self.proj, self.frames, self.w, self.h = proj, [int(x) for x in frames], w, h
        self.images, self.clips, self.bg = images, clips, background
        self.context, self.log = context, log
        self.sts = stems(self.scenes)
        self.cat = catalog.by_id()
        self.check = proj / ".check"
        self.check.mkdir(exist_ok=True)
        self.src: dict[str, str] = {}
        self.regen: set[str] = set()
        self.fallback: dict[str, str] = {}  # stem -> reason
        self.look, self.cards = dict(generate.DEFAULT_LOOK), {}

    # ---- assets ---------------------------------------------------------------
    def copy_assets(self) -> None:
        pub = self.proj / "public"
        for sid, p in self.images.items():
            if Path(p).exists():
                _copy(Path(p), pub / "img" / f"{sid}.png")
        for sid, p in self.clips.items():
            if Path(p).exists():
                _copy(Path(p), pub / "clips" / f"{sid}.mp4")
        if self.bg and Path(self.bg).exists():
            _copy(Path(self.bg), pub / "background.png")

    def assets(self, sid: str) -> list[str]:
        pub = self.proj / "public"
        out = []
        if (pub / "img" / f"{sid}.png").exists():
            out.append(f'staticFile("img/{sid}.png") (illustration, {self.w}x{self.h} or close)')
        if (pub / "clips" / f"{sid}.mp4").exists():
            out.append(f'staticFile("clips/{sid}.mp4") (video clip, exactly scene length, '
                       f'{self.w}x{self.h}; full-frame moving background, muted)')
        if (pub / "background.png").exists():
            out.append('staticFile("background.png") (light paper texture, full frame)')
        return out

    # ---- generation -----------------------------------------------------------
    def _one(self, i: int, error: str = "") -> tuple[str, str | None]:
        s, st = self.scenes[i], self.sts[i]
        card = self.cat[self.cards[s["id"]]]
        try:
            src = generate.scene_module(s, i, len(self.scenes), self.frames[i], self.w, self.h,
                                        card, self.look, self.assets(s["id"]), self.context,
                                        error=error, previous=self.src.get(st, "") if error else "")
        except Exception as e:  # noqa: BLE001 - this scene falls back
            return "", f"generation failed: {e}"
        bad = generate.check_tsx(src)
        return src, ("; ".join(bad) if bad else None)

    def generate(self, idx: list[int], errors: dict[int, str] | None = None) -> dict[int, str]:
        """Write modules for scenes idx in parallel; returns {i: static-check problem}."""
        errors = errors or {}
        with ThreadPoolExecutor(max_workers=min(WORKERS, max(1, len(idx)))) as ex:
            res = list(ex.map(lambda i: self._one(i, errors.get(i, "")), idx))
        problems = {}
        for i, (src, bad) in zip(idx, res):
            st = self.sts[i]
            if i in errors:
                self.regen.add(st)
            if src:
                self.src[st] = src
                self._write(i, src)
            if bad:
                problems[i] = bad
        return problems

    def _write(self, i: int, src: str) -> None:
        (self.proj / "src" / "scenes" / f"{self.sts[i]}.tsx").write_text(src, encoding="utf-8")

    def fail(self, i: int, reason: str) -> None:
        st = self.sts[i]
        self.fallback[st] = reason
        self._write(i, fallback_tsx(self.scenes[i], self.look))

    def retry_or_fail(self, items: dict[int, str]) -> list[int]:
        """Regenerate scenes that have not been regenerated yet; fall back the others.
        Returns the regenerated indices (whose new source still needs checking)."""
        again = {i: e for i, e in items.items() if self.sts[i] not in self.regen}
        for i, e in items.items():
            if i not in again:
                self.fail(i, e)
        if not again:
            return []
        for i in again:
            self.log(f"remotion: {self.scenes[i]['id']} failed, regenerating once: {again[i][:300]}")
        problems = self.generate(list(again), again)
        for i, bad in problems.items():
            self.fail(i, bad)
        return [i for i in again if i not in problems]

    # ---- validation -----------------------------------------------------------
    def typecheck(self) -> dict[int, str]:
        lp = self.check / "tsc.log"
        lp.write_text("")
        try:
            render.typecheck(self.proj, lp)
            return {}
        except RuntimeError:
            text = _tail(lp, 200000)
        by_stem = tsc_errors(text, self.sts)
        if not by_stem:
            raise RuntimeError("remotion: type-check failed outside the scene modules:\n" + text[-2000:])
        return {self.sts.index(st): e for st, e in by_stem.items()}

    def still(self, i: int) -> str | None:
        """Render the scene's midpoint; None = fine, else the error text."""
        st = self.sts[i]
        frm = sum(self.frames[:i]) + self.frames[i] // 2
        out, lp = self.check / f"{st}.png", self.check / f"{st}.still.log"
        lp.write_text("")
        if out.exists():
            out.unlink()
        try:
            render.still(self.proj, frm, out, lp)
        except Exception as e:  # noqa: BLE001
            return f"still render at scene frame {self.frames[i] // 2} failed: {e}\n{_tail(lp)}"
        if not out.exists():
            return "still render produced no image"
        if uniform(out):
            return (f"the frame at scene frame {self.frames[i] // 2} (mid-scene) is one flat colour:"
                    " nothing visible. Content must be on screen by then.")
        return None

    def ts_loop(self) -> None:
        """Type-check; failing scenes get their one regeneration, then the fallback."""
        for _ in range(3):
            errs = self.typecheck()
            if not errs:
                return
            self.retry_or_fail(errs)
        if self.typecheck():
            raise RuntimeError("remotion: type-check still failing after fallbacks")

    def run(self) -> dict:
        self.copy_assets()
        cards = [c for c in self.cat.values()]
        self.look, self.cards = generate.pick_cards(
            self.scenes, self.frames, self.w, self.h, self.images, self.clips,
            bool(self.bg), cards, log=self.log)
        for s in self.scenes:
            self.log(f"remotion: {s['id']} -> card {self.cards[s['id']]}")
        sd = self.proj / "src" / "scenes"
        for p in sd.glob("*.tsx"):
            p.unlink()
        # Fallback placeholders first, so index.ts always resolves while modules are written.
        for i in range(len(self.scenes)):
            self._write(i, fallback_tsx(self.scenes[i], self.look))
        (sd / "index.ts").write_text(index_ts(self.scenes), encoding="utf-8")
        self.write_timeline()
        all_idx = list(range(len(self.scenes)))
        gen_fail = {}
        problems = self.generate(all_idx)
        for i in all_idx:
            if self.sts[i] not in self.src:
                gen_fail[i] = "generation failed"
        for i in gen_fail:
            self.fail(i, "generation failed")
        if problems:
            self.retry_or_fail(problems)
        self.ts_loop()
        for i in all_idx:
            if self.sts[i] in self.fallback:
                continue
            err = self.still(i)
            if err:
                again = self.retry_or_fail({i: err})
                if again:
                    errs = self.typecheck()
                    if i in errs:
                        self.fail(i, errs[i])
                    elif errs:  # another scene broke (should not happen): its fallback
                        for j, e in errs.items():
                            self.fail(j, e)
                    else:
                        err = self.still(i)
                        if err:
                            self.fail(i, err)
        self.ts_loop()
        self.write_timeline()
        for i, s in enumerate(self.scenes):
            st = self.sts[i]
            s["card"] = self.card_of(i)
            if st in self.fallback:
                self.log(f"remotion: {s['id']} fallback to title card ({self.cards[s['id']]}): "
                         f"{self.fallback[st][:300]}")
            else:
                self.log(f"remotion: {s['id']} ok with {s['card']}"
                         f"{' after one regeneration' if st in self.regen else ''}")
        return {"look": self.look, "cards": {s["id"]: s["card"] for s in self.scenes},
                "fallback": {self.scenes[self.sts.index(k)]["id"]: v for k, v in self.fallback.items()}}

    def card_of(self, i: int) -> str:
        return FALLBACK_CARD if self.sts[i] in self.fallback else self.cards[self.scenes[i]["id"]]

    def write_timeline(self) -> None:
        cards = {s["id"]: self.card_of(i) for i, s in enumerate(self.scenes)}
        tl = timeline(self.scenes, self.frames, self.w, self.h, self.look["background"], cards)
        dd = self.proj / "src" / "data"
        dd.mkdir(parents=True, exist_ok=True)
        (dd / "timeline.json").write_text(json.dumps(tl, ensure_ascii=False, indent=1),
                                          encoding="utf-8")


def write_project(job: dict, d: Path, frames: list, w: int, h: int, *, images: dict,
                  clips: dict, background: Path | None, context: str,
                  log: Callable[[str], None]) -> Path:
    proj = Path(d) / "remotion"
    render.copy_template(proj)
    g = _Gen(job, proj, frames, w, h, images or {}, clips or {}, background, context, log)
    res = g.run()
    (g.check / "result.json").write_text(json.dumps(res, ensure_ascii=False, indent=1))
    return proj
