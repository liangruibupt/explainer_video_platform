"""Write the 3D previs parts of a job's Remotion project (docs/PREVIS_CONTRACT.md section 9).

  public/previs/<asset id>.glb    real copies (Remotion's static server refuses symlinks)
  src/data/previs/<stem>.json     ResolvedShot (shots.compile_all output)
  src/scenes/<stem>.tsx           DEFAULTS (overlay texts, palette, grid, shadows) + schema +
                                  Scene = <PrevisShot data={...} {...props}/>, PREVIS = true
  src/scenes/index.ts, src/data/timeline.json   (write_project only)

write_previs() only adds the previs files to an existing project, so a mixed job can keep other
scene modules. write_project() builds a whole previs3d project (template + previs + index +
timeline); captions and audio come from the existing remotion.prepare_media step.
"""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path
from typing import Callable

from ..remotion import project as rproject
from ..remotion import render

PALETTE = {"clay": "#c9c4bb", "accent1": "#d98c5f", "accent2": "#6f9fd8", "accent3": "#8cc084",
           "accent4": "#d8c46f", "glass": "#a9b8c6"}
INK = "#2b2924"
CARD = "previs/3d"
# The template's remotion.config.ts sets the GL backend to "angle", which cannot create a
# WebGL context on this box (contract section 10). A previs project overrides it to swangle.
CONFIG_TS = """import { Config } from "@remotion/cli/config";

// 3D previs project (app/previs/project.py): WebGL needs the swangle backend on this box
// (docs/PREVIS_CONTRACT.md section 10); otherwise the template's settings.
Config.setVideoImageFormat("jpeg");
Config.setChromiumOpenGlRenderer("swangle");
Config.setConcurrency(2);
Config.setOverwriteOutput(true);
"""


def comp_id(scene_id: str) -> str:
    """Remotion composition id of a scene's standalone shot (same rule as Root.tsx)."""
    return "Shot-" + re.sub(r"[^A-Za-z0-9-]", "-", scene_id)


def _key(kind: str, i: int) -> str:
    return f"{'label' if kind == 'label' else 'dim'}_{i}"


def defaults(shot: dict) -> dict:
    out = {"shadows": bool(shot["style"]["shadows"]),
           "grid": shot["set"]["ground"]["kind"] == "grid",
           "background": shot["set"]["background"], "ink": INK, **PALETTE}
    for i, o in enumerate(shot.get("overlays", [])):
        out[_key(o["kind"], i)] = o.get("text", "")
    return out


def schema(shot: dict) -> list:
    f = []
    for i, o in enumerate(shot.get("overlays", [])):
        label = f"标注 {i + 1}" if o["kind"] == "label" else f"尺寸 {i + 1}"
        f.append({"type": "text", "key": _key(o["kind"], i), "label": label, "default": o.get("text", "")})
    f += [{"type": "boolean", "key": "shadows", "label": "阴影", "default": bool(shot["style"]["shadows"])},
          {"type": "boolean", "key": "grid", "label": "网格地面", "default": shot["set"]["ground"]["kind"] == "grid"},
          {"type": "color", "key": "background", "label": "背景", "default": shot["set"]["background"]},
          {"type": "color", "key": "ink", "label": "标注颜色", "default": INK}]
    f += [{"type": "color", "key": k, "label": f"调色板 {k}", "default": v} for k, v in PALETTE.items()]
    return f


def scene_tsx(stem: str, shot: dict) -> str:
    d = json.dumps(defaults(shot), ensure_ascii=False, indent=1)
    s = json.dumps(schema(shot), ensure_ascii=False, indent=1)
    return f"""// GENERATED by app/previs/project.py (docs/PREVIS_CONTRACT.md section 9): one 3D previs shot.
// The camera, poses and timing are in ../data/previs/{stem}.json (shot compiler output).
import React from "react";
import data from "../data/previs/{stem}.json";
import {{ PrevisShot }} from "../lib/previs/PrevisShot";
import type {{ ResolvedShot }} from "../lib/previs/types";
import type {{ PropField }} from "../types";

export const PREVIS = true;
export const DEFAULTS = {d};
export const schema: PropField[] = {s};
export const SCHEMA = schema;
export const Scene: React.FC<Record<string, unknown>> = (props) => (
  <PrevisShot data={{data as unknown as ResolvedShot}} {{...DEFAULTS}} {{...props}} />
);
"""


def _copy(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.is_symlink() or dst.exists():
        dst.unlink()
    shutil.copyfile(src, dst)


def write_previs(proj: Path, shots: dict, glbs: dict) -> list[str]:
    """shots: scene id -> ResolvedShot dict (or a path to its JSON); glbs: asset id -> GLB path.
    Writes public/previs/*.glb, src/data/previs/*.json and src/scenes/*.tsx. Returns the stems."""
    proj = Path(proj)
    for aid, p in glbs.items():
        _copy(Path(p), proj / "public" / "previs" / f"{aid}.glb")
    data = proj / "src" / "data" / "previs"
    data.mkdir(parents=True, exist_ok=True)
    out = []
    for sid, shot in shots.items():
        shot = json.loads(Path(shot).read_text()) if isinstance(shot, (str, Path)) else shot
        stem = rproject.file_stem(sid)
        (data / f"{stem}.json").write_text(json.dumps(shot, ensure_ascii=False, separators=(",", ":")))
        (proj / "src" / "scenes" / f"{stem}.tsx").write_text(scene_tsx(stem, shot), encoding="utf-8")
        out.append(stem)
    return out


def write_project(job: dict, d: Path, frames: list, w: int, h: int, *, shots: dict, glbs: dict,
                  log: Callable[[str], None] = lambda m: None) -> Path:
    """A complete previs3d project in d/'remotion': template, previs files, scenes/index.ts,
    data/timeline.json (card "previs/3d"), swangle config. Sets job['scenes'][i]['card']."""
    proj = Path(d) / "remotion"
    render.copy_template(proj)
    # copy_template never overwrites; the previs renderer and Root.tsx (Shot-* compositions)
    # are fixed template files, so a re-written project always gets the current ones
    for p in [render.TEMPLATE / "src" / "Root.tsx", *(render.TEMPLATE / "src" / "lib" / "previs").glob("*")]:
        _copy(p, proj / p.relative_to(render.TEMPLATE))
    (proj / "remotion.config.ts").write_text(CONFIG_TS)
    scenes = job["scenes"]
    sdir = proj / "src" / "scenes"
    for p in sdir.glob("*.tsx"):  # the template's sample scene
        if p.stem not in {rproject.file_stem(s["id"]) for s in scenes}:
            p.unlink()
    write_previs(proj, shots, glbs)
    for s in scenes:
        s["card"] = CARD
    (sdir / "index.ts").write_text(rproject.index_ts(scenes))
    bg = next(iter(shots.values()), None)
    bg = (json.loads(Path(bg).read_text()) if isinstance(bg, (str, Path)) else bg or {}).get("set", {}).get("background", "#e9e6e1")
    tl = rproject.timeline(scenes, frames, w, h, bg, {s["id"]: CARD for s in scenes})
    (proj / "src" / "data" / "timeline.json").write_text(json.dumps(tl, ensure_ascii=False, indent=1))
    log(f"previs: project written, {len(shots)} shot(s), {len(glbs)} model(s)")
    return proj
